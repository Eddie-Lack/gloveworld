#!/bin/bash
# Usage: tools/patches/mkdebugio.sh
# Compiles debugio.c with the game's compiler, links it at its places in the ROM and writes the
# words and entry points to debugio_code.py, which debugpad2.py reads. Needs `make toolchain` and
# mips-linux-gnu binutils.
set -e
cd "$(dirname "$0")/../.."
out=$(mktemp -d)
trap 'rm -rf "$out"' EXIT

COMPILER_PATH=tools/gcc-2.7.2 tools/gcc-2.7.2/gcc -c -G0 -mcpu=r4000 -mips2 -mmips-as -funsigned-char -O2 \
    -Wa,-EB,-mips3,-mabi=32,-mgp32,-march=vr4300,-mfp32,-mno-shared,--no-pad-sections,-Iinclude \
    tools/patches/debugio.c -o "$out/debugio.o"

# The three regions are ScreenShot, PCcreat and PCclose. ld stops if code does not fit.
cat > "$out/debugio.ld" <<'EOF'
MEMORY {
    screenshot (rx) : ORIGIN = 0x80181B4C, LENGTH = 0x27C
    pccreat (rx) : ORIGIN = 0x8010D4DC, LENGTH = 0x90
    pcclose (rx) : ORIGIN = 0x8010D5FC, LENGTH = 0x68
}
SECTIONS {
    .text : { *(.text) *(.rodata) } > screenshot
    .pccreat : { *(.text.pccreat) } > pccreat
    .pcclose : { *(.text.pcclose) } > pcclose
    /DISCARD/ : { *(.reginfo) *(.MIPS.abiflags) *(.pdr) *(.comment) *(.mdebug*) *(.gnu.attributes) *(.note) }
}
outputMessageBuffer = 0x8025D578;
autoPlayback = 0x801EC7F0;
ReadController = 0x8013407C;
EndTimer = 0x80180534;
__osDisableInt = 0x801C6F70;
__osRestoreInt = 0x801C6F90;
EOF
mips-linux-gnu-ld -EB -T "$out/debugio.ld" "$out/debugio.o" -o "$out/debugio.elf"

python3 - "$out" > tools/patches/debugio_code.py <<'PY'
import subprocess, sys
out = sys.argv[1]
elf = f"{out}/debugio.elf"
print("# Generated by mkdebugio.sh from debugio.c. Do not edit.")
print("SYMBOLS = {")
for line in subprocess.run(["mips-linux-gnu-nm", elf], capture_output=True, text=True).stdout.splitlines():
    addr, kind, name = line.split()
    if kind == "T":
        print(f'    "{name}": 0x{int(addr, 16):08X},')
print("}")
print("# (vram, words) for each block of code")
print("BLOCKS = [")
for sec in ("text", "pccreat", "pcclose"):
    hdr = subprocess.run(["mips-linux-gnu-objdump", "-h", "-j", "." + sec, elf], capture_output=True, text=True).stdout
    vma = int([l for l in hdr.splitlines() if f" .{sec} " in l][0].split()[3], 16)
    subprocess.run(["mips-linux-gnu-objcopy", "-O", "binary", "-j", "." + sec, elf, f"{out}/{sec}.bin"], check=True)
    data = open(f"{out}/{sec}.bin", "rb").read()
    words = [int.from_bytes(data[i:i + 4], "big") for i in range(0, len(data), 4)]
    print(f"    (0x{vma:08X}, [  # .{sec}, {len(data):#x} bytes")
    for i in range(0, len(words), 8):
        print("        " + " ".join(f"0x{w:08X}," for w in words[i:i + 8]))
    print("    ]),")
print("]")
PY
echo "wrote tools/patches/debugio_code.py"
